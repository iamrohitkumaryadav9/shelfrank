"""Write results/slot_evidence.json and docs/slot_evidence.md from the catalogue and ESCI seeds.

No WANDS query is read.
"""

import json
from collections import Counter
from typing import Any

from shelfrank.config import REPO_ROOT, load_config
from shelfrank.data.audit_report import num, pct, table
from shelfrank.data.wands import load_products
from shelfrank.qu import slot_vocab as sv
from shelfrank.text.normalize import tokenize

BORDERLINE = (
    "brushed nickel|matte black|oil rubbed bronze|polished brass|antique brass|chrome|bronze|gold|"
    "silver|stainless steel|espresso|walnut|oak|cherry|natural|velvet|leather|wicker|marble"
).split("|")
# The examples given with the room rule: True means the room word is a slot.
ROOM_EXAMPLES = {
    "dining table": False,
    "kitchen island": False,
    "bathroom vanity": False,
    "outdoor dining set": False,
    "bathroom rug": True,
    "patio umbrella": True,
    "bedroom lamp": True,
}
PATTERNS = ("floral", "striped", "geometric", "plaid", "solid")


def density(path: str, terms: dict, styles: dict, phrases: set) -> dict[str, int]:
    """Queries with at least one catalogue term per slot."""
    queries = (REPO_ROOT / path).read_text(encoding="utf-8").splitlines()
    counts: Counter[str] = Counter(queries=len(queries))
    for query in queries:
        found = {terms[t][0] for t in sv.match_terms(query, terms)}
        if sv.match_terms(query, styles):
            found.add("style")
        if sv.room_slots(query, phrases):
            found.add("room")
        counts.update(found)
        counts["any"] += bool(found)
    return dict(counts)


def collect() -> dict[str, Any]:
    """Gather every figure in the report."""
    products = load_products(REPO_ROOT / load_config("data")["wands"]["raw_dir"])
    values = sv.value_table(products)
    terms = sv.majority_terms(values, ("color", "finish", "material"))
    merged: dict[tuple[str, ...], Counter[str]] = {}
    for value, counts in values.items():
        merged.setdefault(tuple(tokenize(value)), Counter()).update(counts)
    styles = sv.style_terms(values)
    style_terms = {tuple(tokenize(name)): n for name, n in styles.items()}
    phrases = sv.product_type_phrases(products)
    options = {}
    for min_class, min_path in ((1, 10**9), (30, 10**9), (30, 500), (30, 100), (30, 79)):
        found = sv.product_type_phrases(products, min_class, min_path)
        wrong = [q for q, slot in ROOM_EXAMPLES.items() if bool(sv.room_slots(q, found)) != slot]
        options[f"{min_class}/{min_path}"] = wrong
    finish = [t for t, (group, _, _) in terms.items() if group == "finish"]
    return {
        "borderline": {
            v: {g: merged[tuple(tokenize(v))][g] for g in ("color", "finish", "material", "style")}
            for v in BORDERLINE
        },
        "finish_majority_terms": len(finish),
        "union_terms": len(sv.majority_terms(values, sv.UNION, sv.MIN_PRODUCTS)),
        "styles": styles,
        "patterns": {p: merged.get(tuple(tokenize(p)), Counter())["style"] for p in PATTERNS},
        "room_examples": {q: bool(sv.room_slots(q, phrases)) for q in ROOM_EXAMPLES},
        "room_options_wrong": options,
        "density": {
            name: density(f"data/esci/{name}.txt", terms, style_terms, phrases)
            for name in ("esci_prompt_dev", "esci_seed_queries")
        },
    }


def render(e: dict[str, Any]) -> str:
    """Render the report."""
    borderline = []
    for value, counts in e["borderline"].items():
        total = sum(counts.values())
        shares = [f"{num(n)} ({pct(n / total)})" if n else "0" for n in counts.values()]
        borderline.append([value, *shares])
    rooms = [
        [q, "slot" if got else "product type", "slot" if ROOM_EXAMPLES[q] else "product type"]
        for q, got in e["room_examples"].items()
    ]
    labels = {
        "1/1000000000": "every class name",
        "30/1000000000": "classes with 30+ products",
        "30/500": "those, plus path segments with 500+",
        "30/100": "**those, plus path segments with 100+ (implemented)**",
        "30/79": "those, plus path segments with 79+",
    }
    options = [[labels[k], ", ".join(v) or "none"] for k, v in e["room_options_wrong"].items()]
    slots = ("any", "color", "material", "room", "style", "finish")
    densities = [
        [name, d["queries"], *(f"{d.get(s, 0)} ({pct(d.get(s, 0) / d['queries'])})" for s in slots)]
        for name, d in e["density"].items()
    ]
    styles = ", ".join(f"{name} ({num(n)})" for name, n in e["styles"].items())
    patterns = ", ".join(f"{name} ({n})" for name, n in e["patterns"].items())
    return f"""# Slot evidence

Generated by `scripts/slot_evidence.py` from the catalogue and the ESCI seed queries. No WANDS query is
read.

**Every slot value must exist in the catalogue's attribute vocabulary.** Matching is key-agnostic: a colour or
material_finish value is looked up across the union of colour, finish and material keys. The table below
shows why: the same value sits in different keys on different products.

## Which keys hold borderline values

Products per attribute family whose value is exactly the term after normalisation.

{table(["Value", "Colour keys", "Finish keys", "Material keys", "Style keys"], borderline)}

{e["finish_majority_terms"]} values are held mostly by finish keys. Finishes have no slot of their own, because the ESCI
queries contain too few to train or evaluate one. They belong to material_finish. The union vocabulary has
{num(e["union_terms"])} values with at least {sv.MIN_PRODUCTS} products.

## Room rule

A room word is part of the product type when it lies inside a phrase that names a product category and
continues past it. The phrase list is class names and category path segments. Patio, garden, balcony and deck count as outdoor. The
threshold of 100 was chosen while looking at these seven examples, so getting all seven right is not
independent evidence. The blind Round A labels are.

{table(["Example", "Result", "Expected"], rooms)}

Which phrase list reproduces the examples:

{table(["Phrase list", "Examples it gets wrong"], options)}

## Style vocabulary

{len(e["styles"])} names from the style keys, split on "&" and "/", with at least 3 products: {styles}.

Patterns, with the number of products that list them under a style key: {patterns}.

## Slot density in the ESCI queries

Queries with at least one catalogue term. This is a lexicon count and not a label: it has false
positives ("coffee" as a colour) and misses words the catalogue lacks.

{table(["File", "Queries", "Any", "Colour", "Material", "Room", "Style", "Finish"], densities)}
"""


def main() -> None:
    """Collect and write."""
    evidence = collect()
    products = load_products(REPO_ROOT / load_config("data")["wands"]["raw_dir"])
    vocabulary = json.dumps(sv.build_vocabulary(products), indent=1, ensure_ascii=False) + "\n"
    (REPO_ROOT / "data/slot_vocab.json").write_text(vocabulary, encoding="utf-8", newline="\n")
    body = json.dumps(evidence, indent=1, ensure_ascii=False) + "\n"
    (REPO_ROOT / "results/slot_evidence.json").write_text(body, encoding="utf-8", newline="\n")
    page = render(evidence)
    (REPO_ROOT / "docs/slot_evidence.md").write_text(page, encoding="utf-8", newline="\n")
    print(page)


if __name__ == "__main__":
    main()
