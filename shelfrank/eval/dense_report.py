"""Decisions about the fine-tuned encoder, and the page that shows them.

Both rules are in docs/PROTOCOL.md section 8 and were committed before anything was measured.
"""

from collections.abc import Mapping
from typing import Any

from shelfrank.data.audit_report import table
from shelfrank.eval.claims import GAIN, LOSS

SERVING_TOLERANCE = 0.005
METRICS = {
    "ndcg10": "nDCG@10",
    "condensed_ndcg10": "Condensed nDCG@10",
    "judged10": "Judged@10",
    "recall100": "Recall@100",
    "recall100_exact": "Exact-only Recall@100",
}
NAMES = {
    "bm25_multi": "BM25 multi-field, tuned",
    "dense_bge_small": "Dense, off the shelf",
    "dense_bge_small_esci": "Dense, fine-tuned on ESCI",
    "rrf_bge_small": "Hybrid RRF, off the shelf",
    "rrf_bge_small_esci": "Hybrid RRF, fine-tuned",
}


def encoder_choice(dense_verdict: str, hybrid_verdict: str) -> str:
    """Encoder for G2: fine-tuned only on a dense gain without a hybrid loss."""
    adopt = dense_verdict == GAIN and hybrid_verdict != LOSS
    return "bge_small_esci" if adopt else "bge_small"


def serving_choice(int8: float, pytorch: float) -> str:
    """Format for the demo. int8 must stay within the tolerance in either direction."""
    return "int8" if abs(int8 - pytorch) <= SERVING_TOLERANCE else "fp32"


def _signed(row: Mapping[str, float]) -> str:
    return f"{row['mean']:+.3f} [{row['low']:+.3f}, {row['high']:+.3f}]"


def _systems(data: Mapping[str, Any]) -> str:
    rows = []
    for name, label in NAMES.items():
        cells = [data["systems"][name][m] for m in METRICS]
        rows.append([label, *(f"{c['mean']:.3f} [{c['low']:.3f}, {c['high']:.3f}]" for c in cells)])
    ns = [data["systems"]["bm25_multi"][m]["n"] for m in METRICS]
    return table(["System", *METRICS.values()], [*rows, ["*n queries*", *ns]])


def _differences(data: Mapping[str, Any]) -> str:
    rows = []
    for row in data["differences"]:
        label = f"{NAMES[row['system']]} minus {NAMES[row['baseline']]}"
        rows.append([label, *(_signed(row[m]) for m in METRICS), row["verdict"]])
    return table(["Difference", *METRICS.values(), "Verdict"], rows)


def _serving(data: Mapping[str, Any]) -> str:
    rows = []
    for model, kinds in data["serving"].items():
        for kind, r in kinds["formats"].items():
            rows.append(
                [
                    model,
                    kind,
                    f"{r['ndcg10']:.4f}",
                    f"{r['ndcg10'] - kinds['formats']['pytorch']['ndcg10']:+.4f}",
                    f"{r['condensed_ndcg10']:.4f}",
                    f"{r['recall100']:.4f}",
                    f"{r['cosine_mean']:.4f} / {r['cosine_min']:.4f}",
                    f"{r['p50_ms']:.1f}",
                    f"{r['p95_ms']:.1f}",
                    f"{r['megabytes']:.0f}",
                ]
            )
    header = ["Model", "Query encoder", "nDCG@10", "Minus PyTorch", "Condensed", "Recall@100"]
    header += ["Query cosine to PyTorch, mean / min", "p50 ms", "p95 ms", "MB"]
    return table(header, rows)


def render(data: Mapping[str, Any]) -> str:
    """Build docs/dense_dev.md."""
    choices = "\n".join(
        f"- {model}: **{kinds['choice']}**. int8 differs by "
        f"{kinds['formats']['int8']['ndcg10'] - kinds['formats']['pytorch']['ndcg10']:+.4f}."
        for model, kinds in data["serving"].items()
    )
    dense, hybrid = (row["verdict"] for row in data["differences"][:2])
    return f"""# Fine-tuned encoder on the dev fold

Generated by `scripts/make_tables.py` from `results/dense_dev.json`. Do not edit by hand.

**Dev numbers on {data["n_queries"]} queries, used to make choices. They are not results.** Intervals are 95%
percentile bootstrap intervals over queries, and differences are paired. The fine-tuned encoder never saw a
WANDS query or label.

{_systems(data)}

## Differences

The verdict uses standard and condensed nDCG@10 only (PROTOCOL.md section 7). No correction for several
comparisons.

{_differences(data)}

## Encoder of G2

Rule, written before measuring: fine-tuned only if it is a gain as a dense retriever and hybrid RRF with it is
not a loss. Dense verdict: {dense}. Hybrid verdict: {hybrid}. **G2 uses `{data["encoder"]}`.**

## Query encoder for the demo

Rule, written before measuring: int8 only if dense nDCG@10 is within {SERVING_TOLERANCE} of PyTorch, otherwise
fp32 ONNX. Product vectors come from PyTorch throughout. Latency is per query, tokenising included, one query
at a time, over {data["latency_repeats"]} passes of the dev queries on the development laptop's CPU.

{_serving(data)}

{choices}
"""
