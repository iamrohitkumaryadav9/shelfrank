"""Render results/slots_dev.json as docs/slots_dev.md."""

from collections.abc import Mapping
from typing import Any

from shelfrank.data.audit_report import table
from shelfrank.qu.guidelines import SLOTS

SILVER_LABEL = "vs LLM silver labels; human verification pending"


def _all(part: Mapping[str, Any]) -> str:
    cell = part["all"]
    return f"{cell['f1']:.3f} [{cell['low']:.3f}, {cell['high']:.3f}]"


def _slot(cell: Mapping[str, float]) -> str:
    flag = "" if cell["support"] >= 10 else " *"
    return f"{cell['f1']:.2f} ({cell['support']}){flag}"


def _name(run: Mapping[str, Any]) -> str:
    if run["config"] is None:
        return "Lexicon matcher (baseline)"
    c = run["config"]
    lexicon = "with" if c["lexicon_features"] else "without"
    return f"Word tagger {lexicon} lexicon features, window {c['window']}, C {c['c']:g}"


def render(data: Mapping[str, Any]) -> str:
    """Build the page."""
    runs = data["runs"]
    plain = max(
        (r for r in runs if r["config"] and not r["config"]["lexicon_features"]),
        key=lambda r: r["selection"],
    )
    shown = [runs[0], plain, runs[data["best_student"]]]
    rows = [
        [
            ("**" + _name(r) + "**") if r is runs[data["selected"]] else _name(r),
            _all(r["silver"]),
            _all(r["esci"]),
            f"{r['selection']:.3f}",
            f"{r['latency_ms']['p50']:.2f} / {r['latency_ms']['p95']:.2f}",
        ]
        for r in shown
    ]
    header = ["Model", "F1 dev silver", "F1 ESCI held-out", "Selection score", "ms p50 / p95"]
    slots = [
        [_name(r), source, *(_slot(r[key][s]) for s in SLOTS)]
        for r in (runs[0], runs[data["best_student"]])
        for source, key in (("dev silver", "silver"), ("ESCI held-out", "esci"))
    ]
    return f"""# Attribute slots on the dev fold

Generated by `scripts/make_tables.py` from `results/slots_dev.json`. Do not edit by hand.

**Every F1 on this page is {SILVER_LABEL}.** Both references come from the same LLM teacher, so the scores say how
well a small model imitates it. No human label was used (PROTOCOL.md section 6).

Selection rule, set before training: {data["selection_rule"]}. {len(runs)} candidates: the lexicon and {len(runs) - 1}
student configurations, all in the results file. Students train on {data["n_esci_train"]:,} ESCI queries. References:
{data["n_dev"]} dev queries ({data["queries_with_a_slot"]["dev"]} with a slot) and {data["n_esci_held"]} held-out ESCI queries
({data["queries_with_a_slot"]["esci_held"]} with a slot). F1 is over exact spans and all slots, with intervals from resampling
queries.

{table(header, rows)}

Selected: **{_name(runs[data["selected"]])}**.

## Per slot, F1 (support)

{table(["Model", "Reference", *SLOTS], slots)}

\\* support below 10, not interpretable.

The room rule and the metal rule are inside the lexicon matcher, and the selected student reads the matcher's output as
a feature. The student therefore learns when to overrule it.
"""
