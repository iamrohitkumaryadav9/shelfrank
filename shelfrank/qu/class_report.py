"""Render results/class_dev.json as docs/class_dev.md."""

import math
from collections.abc import Mapping
from typing import Any

from shelfrank.data.audit_report import table

ARMS = {"names": "Product names only", "queries": "Seed queries only", "both": "Both"}


def _config(run: Mapping[str, Any]) -> str:
    low, high = run["ngrams"]
    share = "" if run["query_share"] is None else f", query weight {run['query_share']:g}"
    tail = "" if run["tail"] is None else f", last {run['tail']} words"
    return f"n-grams {low}-{high}, alpha {run['alpha']:.0e}{tail}{share}"


def _level(part: Mapping[str, float]) -> str:
    return f"{part['accuracy']:.3f} [{part['low']:.3f}, {part['high']:.3f}]"


def _split(part: Mapping[str, Any], name: str) -> str:
    cell = part.get(name)
    if not cell or not cell["n"]:
        return "n = 0"
    return f"{cell['accuracy']:.3f} (n = {cell['n']})"


def _f1(part: Mapping[str, Any]) -> str:
    if math.isnan(part["macro_f1"]):
        return "undefined (0 classes)"
    return f"{part['macro_f1']:.3f} ({part['macro_f1_classes']} classes)"


def render(data: Mapping[str, Any]) -> str:
    """Build the page."""
    best = [(arm, data["best"][arm]) for arm in ARMS if arm in data["best"]]
    rows = [
        [
            ("**" if arm == data["selected"] else "")
            + ARMS[arm]
            + ("**" if arm == data["selected"] else ""),
            _config(run),
            _level(run["dev"]),
            f"{run['dev']['top3']:.3f}",
            f"{run['dev']['department']:.3f}",
            _level(run["esci"]),
            f"{run['selection']:.3f}",
            f"{run['latency_ms']['p50']:.1f} / {run['latency_ms']['p95']:.1f}",
        ]
        for arm, run in best
    ]
    header = ["Arm", "Configuration", "Dev accuracy", "Dev top-3", "Dev department"]
    header += ["ESCI held-out accuracy", "Selection score", "ms p50 / p95"]
    split_rows = [
        [
            ARMS[arm],
            _split(run["dev"], "seeded"),
            _split(run["dev"], "names_only"),
            _f1(run["dev"]),
            _f1(run["esci"]),
        ]
        for arm, run in best
    ]
    split_header = ["Arm", "Dev, classes with a seed query", "Dev, classes without one"]
    split_header += ["Macro-F1 dev", "Macro-F1 ESCI"]
    top_dev = max(data["runs"], key=lambda r: r["dev"]["accuracy"])
    chosen = data["best"][data["selected"]]
    if top_dev["dev"]["accuracy"] > chosen["dev"]["accuracy"]:
        note = (
            f"The best dev accuracy of any configuration is {top_dev['dev']['accuracy']:.3f} ({ARMS[top_dev['arm']]}, "
            f"{_config(top_dev)}), against {chosen['dev']['accuracy']:.3f} for the selected one. The rule is kept."
        )
    else:
        note = "The selected configuration also has the best dev accuracy."
    return f"""# Product-class student on the dev fold

Generated by `scripts/make_tables.py` from `results/class_dev.json`. Do not edit by hand.

Dev accuracy is **agreement with Wayfair's assigned query class** ({best[0][1]["dev"]["n"]} queries, of which
{data["dev_reference_other"]} have a class outside the taxonomy and count as "other"). ESCI accuracy is agreement with the
teacher on {data["esci_reference"]} ({best[0][1]["esci"]["n"]} queries). No student saw a WANDS query. The seed arms train
on {data["seed_training_queries"]:,} teacher-labelled ESCI queries covering {data["seeded_classes"]} labels.

**Selection rule, set before training:** {data["selection_rule"]}. {len(data["runs"])} configurations, all in the results
file. Dev numbers are optimistic, because configurations are chosen partly on them.

## Best configuration of each arm, by the rule

{table(header, rows)}

Selected: **{ARMS[data["selected"]]}**. {note}

## Where the seed helps

{table(split_header, split_rows)}

Macro-F1 covers classes with at least 5 reference queries.
"""
