"""Render the "More like this" results as docs/similar.md."""

from collections.abc import Mapping
from typing import Any

from shelfrank.data.audit_report import table
from shelfrank.eval.claims import holm

NAMES = {
    "bm25": "BM25 on product text",
    "bge_small": "Dense, off the shelf",
    "bge_small_esci": "Dense, fine-tuned on ESCI",
    "rrf": "Hybrid RRF",
    "rerank": "RRF re-ranked",
}
METRICS = {
    "ndcg10": "nDCG@10",
    "condensed_ndcg10": "Condensed nDCG@10",
    "recall10": "Recall@10",
    "mrr": "MRR",
}


def _level(c: Mapping[str, float]) -> str:
    return f"{c['mean']:.3f} [{c['low']:.3f}, {c['high']:.3f}]"


def _gap(c: Mapping[str, float]) -> str:
    return f"{c['mean']:+.3f} [{c['low']:+.3f}, {c['high']:+.3f}]"


def adjusted(data: Mapping[str, Any]) -> list[float]:
    """Holm-adjusted p of each comparison's claim."""
    out = holm({str(i): d["p"] for i, d in enumerate(data["differences"])})
    return [out[str(i)] for i in range(len(data["differences"]))]


def section(data: Mapping[str, Any]) -> str:
    """Tables of one split."""
    rows = [
        [
            NAMES[n],
            *(_level(data["systems"][n]["query_mean"][m]) for m in METRICS),
            f"{data['systems'][n]['seed_mean']['ndcg10']['mean']:.3f}",
        ]
        for n in NAMES
    ]
    ceiling = ["*Ceiling*", "1.000", "1.000", f"{data['recall10_ceiling']:.3f}", "1.000", "1.000"]
    ps = adjusted(data)
    gaps = [
        [
            f"{NAMES[d['system']]} minus {NAMES[d['baseline']]}",
            _gap(d["ndcg10"]),
            _gap(d["condensed_ndcg10"]),
            _gap(d["recall10"]),
            d["verdict"],
            f"{p:.4f}",
        ]
        for d, p in zip(data["differences"], ps, strict=True)
    ]
    label = (
        "dev (used to choose settings, not a result)"
        if data["split"] == "dev"
        else "folds 1 to 4 (primary)"
    )
    weights = ", ".join(f"{k} {v:g}" for k, v in data["weights"].items())
    return f"""## {label}

{data["n_queries"]} queries with at least 2 Exact products, {data["n_seeds"]:,} seed products. RRF encoder: `{data["encoder"]}`.
Re-ranker weights: {weights}.

{table(["System", *METRICS.values(), "nDCG@10, mean over seeds"], [*rows, ceiling])}

{table(["Difference", "nDCG@10", "Condensed nDCG@10", "Recall@10", "Verdict", "Holm p"], gaps)}
"""


def render(dev: Mapping[str, Any], primary: Mapping[str, Any] | None) -> str:
    """Build the page."""
    parts = [section(primary)] if primary else ["The primary result comes after the freeze."]
    return f"""# More like this: item-to-item substitutes

Generated by `scripts/make_tables.py`. Do not edit by hand. Design: [PROTOCOL.md](PROTOCOL.md) section 16.

For a seed product, the catalogue is ranked by how well each product could replace it. The reference is human: products
labelled Exact for the same query form a substitute set. Each query counts once, and intervals resample queries.

{chr(10).join(parts)}
{section(dev)}
{len(dev["grid"])} weight settings were tried on dev, all in `results/similar_dev.json`.

## Limits

- Sets are defined by relevance to one query, not by co-views or purchases. This measures **substitutability**, not
  complementarity or engagement.
- A product that could replace the seed but was never judged Exact for that query counts as wrong. The condensed
  columns leave unjudged products out.
- The judgment pool favoured class match, so shared class is the term most exposed to pool bias.
"""
