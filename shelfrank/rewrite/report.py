"""Render the rewriting results as docs/rewriting.md."""

from collections.abc import Mapping, Sequence
from typing import Any

from shelfrank.data.audit_report import table
from shelfrank.eval.final_report import adjusted, claimed

NAMES = {
    "ltr": "LTR",
    "rrf": "Hybrid RRF",
    "ltr_triggered": "LTR with triggered rewriting",
    "rrf_triggered": "Hybrid RRF with triggered rewriting",
    "ltr_all_rewritten": "LTR, every query rewritten",
    "rrf_all_rewritten": "Hybrid RRF, every query rewritten",
    "oracle_worst": "Oracle: rewrite the truly worst queries (uses labels)",
    "oracle_helped": "Oracle: rewrite only where it helps (uses labels)",
}


def _gap(c: Mapping[str, float]) -> str:
    return f"{c['mean']:+.3f} [{c['low']:+.3f}, {c['high']:+.3f}]"


def _rows(rows: Sequence[Mapping[str, Any]], corrected: bool) -> list[list[Any]]:
    ps = adjusted(rows) if corrected else [None] * len(rows)
    return [
        [
            NAMES[r["system"]],
            r["n"],
            _gap(r["ndcg10"]),
            _gap(r["condensed_ndcg10"]),
            f"{p:.4f}" if p is not None else "",
            claimed(r, p) if p is not None else r["verdict"],
        ]
        for r, p in zip(rows, ps, strict=True)
    ]


def section(data: Mapping[str, Any]) -> str:
    """One split."""
    label = (
        "Dev (chose the trigger, not a result)"
        if data["split"] == "dev"
        else "Primary: folds 1 to 4"
    )
    header = [
        "System against itself without rewriting",
        "n",
        "nDCG@10",
        "Condensed nDCG@10",
        "Holm p",
        "Verdict",
    ]
    levels = [
        [
            NAMES[n],
            f"{v['ndcg10']:.3f} [{v['interval']['low']:.3f}, {v['interval']['high']:.3f}]",
            f"{v['condensed_ndcg10']:.3f}",
            f"{v['judged10']:.3f}",
            f"{v['exact10_share']:.3f}",
        ]
        for n, v in data["levels"].items()
    ]
    harm, cost, ms = data["harm"], data["cost"], data["latency_ms"]
    latency = (
        "not measured"
        if ms["p50"] is None
        else f"p50 {ms['p50']:.0f} ms, p95 {ms['p95']:.0f} ms (n = {ms['n']})"
    )
    share = data["exact10_share_on_slice"]
    return f"""## {label}

Triggered: {data["triggered"]} of {data["n"]} queries ({data["triggered"] / data["n"]:.0%}).

{table(["System", "nDCG@10", "Condensed", "Judged@10", "Exact@10 / ceiling"], levels)}

**All queries**

{table(header, _rows(data["overall"], True))}

**Triggered queries only** (exploratory, not corrected)

{table(header, _rows(data["slice"], False))}

Exact@10 / ceiling on the triggered queries: {share["ltr"]:.3f} without and {share["ltr_all_rewritten"]:.3f} with rewriting.

**Harm on triggered queries:** {harm["worse"]} worse, {harm["better"]} better, {harm["same"]} the same (LTR, nDCG@10). The largest loss is
{min([d for _, d in harm["worst"]], default=0):+.3f} and the largest gain {max([d for _, d in harm["best"]], default=0):+.3f}.

**Bounds that use labels** (not systems)

{table(header, [*_rows([data["always"]], False), *_rows(data["oracle"], False)])}

**Cost and latency:** Rs {cost["inr_per_call"]:.4f} per call, Rs {cost["inr_per_1000_rewritten"]:.1f} per 1,000 rewritten queries, Rs
{cost["inr_per_1000_queries"]:.1f} per 1,000 searches at this trigger rate. Time of the API call: {latency}. That is added to the search
when a rewrite is not cached.
"""


def render(dev: Mapping[str, Any], primary: Mapping[str, Any] | None) -> str:
    """Build the page."""
    parts = [section(primary)] if primary else []
    trigger = dev["trigger"]
    return f"""# LLM query rewriting on hard queries

Generated by `scripts/make_tables.py`. Do not edit by hand.

A query is rewritten when `{trigger["signal"]}` is on the hard side of {trigger["threshold"]:.4g}. The signal exists at serving time
and uses no label. {len(dev["trigger_log"])} triggers were tried on dev by one rule (`configs/frozen_rewrite.yaml`), all logged in
`results/rewrite_dev.json`, and the choice was committed before the primary queries were scored. The main results of the ranker were known
by then, as aggregates. Rewrites are fused into BM25 and dense retrieval. The ranker's text features still describe the query as typed.

{chr(10).join(parts)}
{section(dev)}"""
