"""Render results/suggest.json as docs/suggest.md."""

from collections.abc import Mapping
from typing import Any

from shelfrank.data.audit_report import table

NAMES = {
    "frequency_only": "Most frequent words (baseline)",
    "ngram": "N-gram back-off over the query trie",
    "ngram_class_prior": "N-gram with class prior",
}


def _level(c: Mapping[str, float]) -> str:
    return f"{c['mean']:.3f} [{c['low']:.3f}, {c['high']:.3f}]"


def _gap(c: Mapping[str, float]) -> str:
    return f"{c['mean']:+.3f} [{c['low']:+.3f}, {c['high']:+.3f}]"


def render(data: Mapping[str, Any]) -> str:
    """Build the page."""
    lengths = list(data["prefix_words"])
    rows = [
        [label, *(_level(data["prefix_words"][n]["mrr"][name]) for n in lengths)]
        for name, label in NAMES.items()
    ]
    rows.append(["*n held-out cases*", *(data["prefix_words"][n]["n"] for n in lengths)])
    rows.append(
        [
            "*next word seen in training*",
            *(
                f"{data['prefix_words'][n]['next_word_in_training_vocabulary']:.0%}"
                for n in lengths
            ),
        ]
    )
    gaps = [
        [
            "N-gram minus frequency",
            *(_gap(data["prefix_words"][n]["ngram_minus_frequency"]) for n in lengths),
        ],
        [
            "Class prior minus n-gram",
            *(_gap(data["prefix_words"][n]["class_prior_minus_ngram"]) for n in lengths),
        ],
    ]
    header = [
        "MRR of the true next word",
        *(f"{n} word{'s' if n != '1' else ''} typed" for n in lengths),
    ]
    tuning = ", ".join(f"{r['class_weight']:g}: {r['mrr']:.3f}" for r in data["tuning"])
    weight = data["class_weight"]
    note = (
        "The prior was not useful in cross-validation, so its weight is 0 and it equals the plain n-gram model."
        if not weight
        else f"Weight {weight:g} was chosen."
    )
    return f"""# Search suggestions

Generated by `scripts/make_tables.py` from `results/suggest.json`. Do not edit by hand.

**There is no popularity here.** The corpus is a set of unique ESCI queries with no counts, so nothing in it says how
often people search for something. Completions are ranked by how many *different* queries continue a prefix that way.
A production system would rank by real query logs, and this evaluation cannot show what that would give.

The corpus is also small: {data["train_queries"]:,} ESCI queries (the labelled seed), because ESCI is not processed on the
development machine. Held out: {data["held_out_queries"]} queries. No WANDS query is used.

{table(header, rows)}

{table(["Difference (paired, 95% CI)", *header[1:]], gaps)}

MRR counts the true next word within the top {data["k"]}. Class-prior weights tried by 5-fold cross-validation inside the
training queries, with their MRR: {tuning}. {note} N-gram latency: p50 {data["ngram_latency_ms"]["p50"]:.2f} ms, p95
{data["ngram_latency_ms"]["p95"]:.2f} ms per prefix.

The last row of the first table is an upper limit: a word that never occurs in the corpus cannot be suggested.
"""
