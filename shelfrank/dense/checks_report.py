"""Render results/phase3_checks.json as docs/phase3_checks.md."""

from collections.abc import Mapping
from typing import Any

from shelfrank.data.audit_report import table

NAMES = {"bge_small": "Off the shelf", "bge_small_esci": "Fine-tuned"}


def _yes(value: bool) -> str:
    return "yes" if value else "**no**"


def _pooling(data: Mapping[str, Any]) -> str:
    models = [data["pooling"][m] for m in NAMES]
    tensors = [len(data["pooler_tensors_in_file"][m]) for m in NAMES]
    rows = [
        ["Pipeline", *(", ".join(m["modules"]) for m in models)],
        ["Pooling mode", *(m["pooling"] for m in models)],
        ["Pooler tensors in the weight file", *tensors],
        [
            "Largest difference from the first token of `last_hidden_state`, 5 texts",
            *(f"{m['max_difference_from_first_token']:.1e}" for m in models),
        ],
        [
            "Cosine to `pooler_output` (control), lowest to highest",
            *(
                f"{m['cosine_to_pooler_output'][0]:.2f} to {m['cosine_to_pooler_output'][1]:.2f}"
                for m in models
            ),
        ],
        [
            "Bit-identical with the layer present",
            *(_yes(m["identical_with_layer"]) for m in models),
        ],
        [
            "Bit-identical with it overwritten by noise",
            *(_yes(m["identical_noised"]) for m in models),
        ],
        ["Bit-identical with it removed", *(_yes(m["identical_removed"]) for m in models)],
    ]
    return table(["Check", *NAMES.values()], rows)


def _embeddings(data: Mapping[str, Any]) -> str:
    models = [data["embeddings"][m] for m in NAMES]

    def sofas(m: Mapping[str, Any]) -> str:
        with_class = [c for c in m["grey_sofa_classes"] if c]
        hits = sum("Sofas" in c or "Sectionals" in c for c in with_class)
        return f"{hits} of {len(with_class)}"

    rows = [
        ["Manifest matches model, texts and count", *(_yes(m["manifest_matches"]) for m in models)],
        ["Rows and dimensions", *(f"{m['shape'][0]:,} x {m['shape'][1]}" for m in models)],
        [
            "40 random rows encoded again, lowest cosine to the saved row",
            *(f"{m['reencoded_min_cosine']:.7f}" for m in models),
        ],
        [
            "**Mean pairwise cosine**, 1,000 random products",
            *(f"**{m['pairwise_mean']:.3f}**" for m in models),
        ],
        ["Standard deviation", *(f"{m['pairwise_sd']:.3f}" for m in models)],
        ["Same-class mean cosine", *(f"{m['same_class_mean']:.3f}" for m in models)],
        ["Different-class mean cosine", *(f"{m['other_class_mean']:.3f}" for m in models)],
        [
            "AUC, same-class pairs against different-class pairs",
            *(f"{m['class_auc']:.3f}" for m in models),
        ],
        [
            "Top-10 neighbours in the same class",
            *(f"{m['neighbours_same_class']:.3f}" for m in models),
        ],
        [
            '"grey sofa": top-10 products classed as sofas, of those with a class',
            *(sofas(m) for m in models),
        ],
    ]
    return table(["Check", *NAMES.values()], rows)


def render(data: Mapping[str, Any], training: Mapping[str, Any]) -> str:
    """Build the page."""
    source = data["provenance"]
    files = source["code_files_match"]
    train = training["train"]
    onnx = training["onnx"]["bge_small_esci"]["cosine_to_pytorch"]
    rows = [
        ["Git commit recorded in the package", f"`{source['commit'][:7]}`"],
        ["Embedded code files identical to that commit", f"{sum(files.values())} of {len(files)}"],
        [
            "Training settings equal `configs/esci.yaml` at that commit",
            _yes(source["training_settings_match"]),
        ],
        ["Data settings equal it too", _yes(source["data_settings_match"])],
        ["Base model and revision as pinned", _yes(source["base_model_matches"])],
        ["SHA-256 of the weights", f"`{data['weights_sha256'][:16]}...`"],
    ]

    def logged(key: str) -> str:
        return "logged" if data[key] else "not logged"

    run = [
        ["Steps", f"{train['step']:,} of {train['total']:,}"],
        ["Triplets", f"{training['triplets']:,}"],
        ["Loss, mean of steps 1 to 50", f"{train['history'][0][1]:.3f}"],
        ["Loss, last 50-step mean (to step 2,700)", f"{train['history'][-2][1]:.3f}"],
        ["Wall time", logged("run_log_in_package")],
        ["Resumes after a disconnect", logged("run_log_in_package")],
        [
            "Held-out ESCI nDCG before, after",
            f"{training['held_out_ndcg_before']:.4f}, {training['held_out_ndcg_after']:.4f}",
        ],
    ]
    return f"""# Checks of the Phase 3 model

Generated by `scripts/make_tables.py` from `results/phase3_checks.json` and `results/finetune_esci.json`. Do not edit
by hand. No relevance label and no WANDS query is used here.

## Finding 1: the pooler warning is harmless

Loading the fine-tuned model printed that `pooler.dense` was newly initialised. Our training saved no pooler
layer, because bge takes the first token and never reads that layer. The off-the-shelf file does contain
those weights, so loading it the same way prints **no** warning. The two models therefore differ in the
warning, and the warning alone does not show that it is harmless. The last three rows below do.

{_pooling(data)}

The local model is now loaded without the layer, which removes the warning. `tests/test_encoder.py` checks on a
tiny model that vectors are bit-identical with the layer absent, random or noised.

Code path: `scripts/encode_products.py` calls `load_sentence_transformer` in `shelfrank/dense/encoder.py`, which
runs `SentenceTransformer.encode`. That follows `modules.json`.

An earlier message in this project said off-the-shelf bge-small prints the reverse warning. That was wrong: it
came from a test script that loaded it without a pooler.

## Finding 2: the mean cosine is lower, and class separation is not

The mean pairwise cosine does not look like the off-the-shelf model's. It is not near 0 either, and products of
one class stay closer to each other than to other products. This is consistent with contrastive training
spreading the vectors out, which lowers all cosines. Ranking uses only their order.

{_embeddings(data)}

The two models share {data["shared_neighbours"]:.0%} of their top-10 neighbours. Same-class figures use 1,000
random products that have a class. The passage text contains the class name, so these rows show that the vectors
hold structure. **They do not show relevance**, which is measured in [dense_dev.md](dense_dev.md).

## Where the model came from

{table(["Check", "Result"], rows)}

## The training run

{table(["Item", "Value"], run)}

Wall time and resumes were only printed in the notebook, and the output was not kept. They are not estimated. The
notebook now writes them to Drive, with every step's loss and {"20"} reference vectors, for any future run.

**The held-out ESCI result is in-domain only and has no confidence interval.** The per-query scores were not saved,
so a paired interval cannot be computed. It says nothing about WANDS. The notebook now saves them.

## int8

The file exists and loads. Its cosine to PyTorch in Colab was {onnx["mean"]:.3f} on average and {onnx["min"]:.3f} at the
lowest, so it was not used until measured ([dense_dev.md](dense_dev.md)).
"""
