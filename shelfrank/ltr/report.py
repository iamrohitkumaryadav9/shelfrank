"""Render the dev-fold ranking experiments as Markdown."""

from collections.abc import Mapping
from typing import Any

Systems = Mapping[str, Mapping[str, Any]]


def _score(cell: Mapping[str, float]) -> str:
    return f"{cell['mean']:.3f} [{cell['low']:.3f}, {cell['high']:.3f}]"


def _difference(cell: Mapping[str, float]) -> str:
    return f"{cell['mean']:+.3f} [{cell['low']:+.3f}, {cell['high']:+.3f}]"


def _level_rows(systems: Systems, names: list[str]) -> list[str]:
    rows = ["| System | nDCG@10 | Condensed nDCG@10 | Judged@10 |", "| --- | --- | --- | --- |"]
    for name in names:
        s = systems[name]
        rows.append(
            f"| {name} | {_score(s['ndcg10'])} | {_score(s['condensed_ndcg10'])} "
            f"| {s['judged10']['mean']:.3f} |"
        )
    return rows


def _difference_rows(systems: Systems, names: list[str], reference: str) -> list[str]:
    rows = [
        "| Configuration | nDCG@10 | Condensed nDCG@10 | Verdict |",
        "| --- | --- | --- | --- |",
    ]
    for name in names:
        d = systems[name]["versus"][reference]
        rows.append(
            f"| {name} | {_difference(d['ndcg10'])} | {_difference(d['condensed_ndcg10'])} "
            f"| {d['verdict']} |"
        )
    return rows


def _encoder_section(results: Mapping[str, Any]) -> list[str]:
    """The encoder that the rule did not choose, shown whatever it scores."""
    if "other_encoder" not in results:
        return []
    systems = results["systems"]
    own = systems["other_encoder"]["versus"]["hybrid_rrf_other_encoder"]
    return [
        f"## Ablation: `{results['other_encoder']}` in candidates and G2",
        "",
        f"The encoder rule chose `{results['encoder']}` ([dense_dev.md](dense_dev.md)). Same training "
        "option, so it was not chosen for this encoder.",
        "",
        *_level_rows(systems, ["hybrid_rrf_other_encoder", "other_encoder"]),
        "",
        f"- Against the chosen option: {_verdict(systems['other_encoder']['versus'], results['chosen'])}",
        f"- Against hybrid RRF with the same encoder: {_difference(own['ndcg10'])} standard, "
        f"{_difference(own['condensed_ndcg10'])} condensed, {own['verdict']}.",
        "",
    ]


def _verdict(versus: Mapping[str, Any], reference: str) -> str:
    d = versus[reference]
    return (
        f"{_difference(d['ndcg10'])} standard, {_difference(d['condensed_ndcg10'])} condensed, "
        f"{d['verdict']}."
    )


def _heading(results: Mapping[str, Any]) -> list[str]:
    """What kind of run this is, and what that allows."""
    stage = results.get("stage")
    if stage is None:
        return [
            "# Ranking experiments on the dev fold (exploratory)",
            "",
            "Superseded by the interim run. Kept because every dev run stays visible.",
            "",
        ]
    fixes = "; ".join(results["bug_fixes"]) or "none"
    lines = [f"# Dev comparison: {stage.upper()}", ""]
    if stage == "interim":
        lines += [
            "**INTERIM. G4 (attribute match) is off.** No design change follows from this run except "
            "logged bug fixes. One FINAL dev run comes after Round A, with G4 on.",
            "",
        ]
    return [
        *lines,
        f"Selection rule, fixed before the run: {results['selection_rule']}. Encoder of G2 and of hybrid "
        f"RRF: `{results['encoder']}`. Class student: {results['class_student']}. Bug-fix reruns: {fixes}.",
        "",
    ]


def render(results: Mapping[str, Any], source: str = "ltr_dev") -> str:
    """Build the page from a results file."""
    systems: Systems = results["systems"]
    chosen = results["chosen"]
    options = [n for n in systems if n.startswith("full_")]
    ablated = [n for n in systems if n.startswith(("without_", "only_"))]
    curve = [f"train_on_{n}" for n in results["learning_curve"]]
    gain = systems[chosen]["gain_by_group"]
    baselines = ["bm25_multi", "dense", "hybrid_rrf"]
    lines = [
        *_heading(results),
        f"Generated by `scripts/make_tables.py` from `results/{source}.json`.",
        "",
        f"{results['n_queries']} dev queries, {results['rows']:,} candidate pairs "
        f"({results['judged_share']:.0%} judged), groups {', '.join(results['groups'])}. "
        "Every ranking is out-of-fold inside the dev fold, so a model trains on "
        "about 72 queries. The final run trains on about 384. **These are dev numbers used to make "
        "choices. They are not results.**",
        "",
        f"## Levels, with the option that has the highest sum of both metrics: `{chosen}`",
        "",
        *_level_rows(systems, [*baselines, chosen]),
        "",
        "## The chosen option against each baseline",
        "",
        f"- Hybrid RRF (primary comparison): {_verdict(systems[chosen]['versus'], 'hybrid_rrf')}",
        f"- Tuned BM25 (secondary): {_verdict(systems[chosen]['versus'], 'bm25_multi')}",
        "",
        "## All training options against hybrid RRF",
        "",
        "The option was picked on the same 96 queries it is scored on, so its score is optimistic.",
        "",
        *_difference_rows(systems, options, "hybrid_rrf"),
        "",
        "## Other methods and learning curve, against the chosen option",
        "",
        *_difference_rows(systems, ["pointwise", "label_gain_013", *curve], chosen),
        "",
        "## Feature groups, against the chosen option",
        "",
        *_difference_rows(systems, ablated, chosen),
        "",
        "Share of split gain by group: "
        + ", ".join(f"{g} {v:.0%}" for g, v in sorted(gain.items()))
        + ".",
        "",
        *_encoder_section(results),
    ]
    return "\n".join(lines)
